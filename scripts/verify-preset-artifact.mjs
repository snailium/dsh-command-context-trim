#!/usr/bin/env node
/**
 * Verify the artifact `/trim preset` writes, against a real dsh installation.
 *
 * It takes the shipped `dsh-web-app/presets/standard.patch.yml` plugin list as the
 * clone source (which is what `agentPresets.readDocument()` dumps, modulo the dump's
 * formatting), runs the generator over it, and then parses the result with the YAML
 * stack the harness itself ships. That proves the written row is structurally what
 * the loader will read — the one thing unit tests over strings cannot prove.
 *
 * Read-only: it never writes into the installation or a home.
 *
 *   node scripts/verify-preset-artifact.mjs [<dsh install dir>]
 *
 * Without an argument it resolves the `dsh` on PATH.
 *
 * @module dsh-command-context-trim/scripts/verify-preset-artifact
 */
import { readFileSync, realpathSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { planCompactionTuning } from '../lib/compaction-spec.js';
import { renderPresetRow, setEntryConfig, upsertMarkerBlock } from '../lib/preset-yaml.js';

const install = resolveInstall(process.argv[2]);
const requireFromInstall = createRequire(join(install, 'node_modules'));
const YAML = loadYaml(requireFromInstall);

const presetFile = join(install, 'node_modules/@deepseek-ai/dsh-web-app/presets/standard.patch.yml');
const base = extractPlugins(readFileSync(presetFile, 'utf8'));
if (base === null) fail(`could not find a plugins list in ${presetFile}`);

const routes = [
	{ provider: 'b70-sycl', model: '/models/Qwen3.8-27B-Q4_K_M.gguf', contextWindow: 131072, maxTokens: 16384 },
	{ provider: 'bonsai-8gb', model: '/home/gwang/bonsai2/models/mtp-lean.gguf', contextWindow: 40960, maxTokens: 8192 },
	{ provider: 'opencode-go', model: 'deepseek-v4.1-flash', contextWindow: 1000000, maxTokens: 384000 }
];
const plan = planCompactionTuning({ routes, targetRatio: 0.8, summarizationRoute: { provider: 'opencode-go', model: 'deepseek-v4.1-flash' } });
const spliced = setEntryConfig(base, 'compaction-basic', plan.config);
if (spliced === null) fail('the shipped standard preset declares no compaction-basic entry');

const row = renderPresetRow({
	rowId: 'preset-standard-tuned',
	presetId: 'standard-tuned',
	name: 'Standard (tuned 80%)',
	description: 'Generated by /trim preset: compaction fires at 80 % of each routed window, summarization on opencode-go/deepseek-v4.1-flash.',
	order: 1.5,
	pluginsYaml: spliced
});
const file = upsertMarkerBlock('# an existing user patch row\n- id: web-search-deepseek\n  disabled: true\n', 'preset-standard-tuned', row).text;

// ── parse with the harness's own YAML stack ─────────────────────────────────
let parsed;
try {
	parsed = YAML.parse(file);
} catch (error) {
	fail(`the generated patch file does not parse: ${error.message}\n\n${file.slice(0, 400)}`);
}
assert(Array.isArray(parsed), 'the profile patch must be a YAML sequence');
const inserted = parsed.find((entry) => Array.isArray(entry?.insert) && entry.insert.some((row) => row.id === 'preset-standard-tuned'));
assert(inserted !== undefined, 'the generated insert row is missing after parsing');
const presetRow = inserted.insert.find((row) => row.id === 'preset-standard-tuned');
assert(presetRow.name === '@deepseek-ai/dsh-agent-preset', `unexpected plugin name ${presetRow.name}`);
const preset = presetRow.config;
assert(preset.id === 'standard-tuned', 'preset id missing');
assert(typeof preset.name === 'string' && preset.name.length > 0, 'preset name missing');
assert(typeof preset.order === 'number', 'preset order must be numeric');
assert(Array.isArray(preset.plugins) && preset.plugins.length > 10, `expected the full cloned composition, got ${preset.plugins?.length} entries`);

const compactionGroup = preset.plugins.find((entry) => entry.id === 'compaction');
assert(compactionGroup !== undefined, 'the cloned composition lost its compaction group');
assert(compactionGroup.isolate?.compaction === true, 'the compaction isolate realm must survive the clone');
const basic = compactionGroup.config.find((entry) => entry.id === 'compaction-basic');
assert(basic !== undefined, 'compaction-basic missing from the cloned group');
assert(basic.config.thresholdRatio === 0.8, `thresholdRatio is ${basic.config.thresholdRatio}`);
assert(basic.config.headroomTokens === 0, 'top-level headroom must be zero so the ratio decides');
assert(basic.config.maxTokens === 384000, `maxTokens is ${basic.config.maxTokens}`);
assert(basic.config.summarizationProvider === 'opencode-go', 'summarization route missing');
assert(Array.isArray(basic.config.modelPolicies) && basic.config.modelPolicies.length === 3, 'one policy per route expected');
assert(basic.config.modelPolicies[0].headroomTokens === 9831, `b70-sycl headroom is ${basic.config.modelPolicies[0].headroomTokens}`);

const baseParsed = YAML.parse(base);
assert(preset.plugins.length === baseParsed.length, `clone changed the plugin count: ${baseParsed.length} → ${preset.plugins.length}`);
const untouched = preset.plugins.filter((entry) => entry.id !== 'compaction').length;
assert(untouched === baseParsed.filter((entry) => entry.id !== 'compaction').length, 'clone altered an unrelated entry');

console.log(`OK  ${install}`);
console.log(`    base: ${baseParsed.length} plugin entries from ${presetFile.replace(install, '<install>')}`);
console.log(`    row:  preset-standard-tuned → ${preset.plugins.length} entries, compaction-basic thresholdRatio ${basic.config.thresholdRatio}, ${basic.config.modelPolicies.length} model policies`);
console.log(`    file: ${file.split('\n').length} lines, parsed by the harness's own YAML stack`);

function resolveInstall(argument) {
	if (argument !== undefined) return resolve(argument);
	for (const dir of (process.env.PATH ?? '').split(':')) {
		if (dir.length === 0) continue;
		try {
			return dirname(dirname(realpathSync(join(dir, 'dsh'))));
		} catch {
			/* not this directory */
		}
	}
	fail('could not find dsh on PATH; pass the installation directory explicitly');
}

function loadYaml(requireFrom) {
	for (const id of ['yaml', 'js-yaml']) {
		try {
			const module = requireFrom(id);
			if (typeof module.parse === 'function') return module;
			if (typeof module.load === 'function') return { parse: (text) => module.load(text) };
		} catch {
			/* try the next one */
		}
	}
	fail('no YAML parser found in the dsh installation (looked for yaml and js-yaml)');
}

/** Cut the `plugins:` sequence out of a shipped preset patch and dedent it to column 0. */
function extractPlugins(text) {
	const lines = text.split('\n');
	const index = lines.findIndex((line) => /^ {8}plugins:\s*$/u.test(line));
	if (index < 0) return null;
	const body = [];
	for (let cursor = index + 1; cursor < lines.length; cursor += 1) {
		const line = lines[cursor];
		if (line.trim().length === 0) {
			body.push('');
			continue;
		}
		const indent = line.length - line.trimStart().length;
		if (indent < 10) break;
		body.push(line.slice(10));
	}
	while (body.length > 0 && body[body.length - 1].trim().length === 0) body.pop();
	return `${body.join('\n')}\n`;
}

function assert(condition, message) {
	if (!condition) fail(message);
}

function fail(message) {
	process.stderr.write(`FAIL  ${message}\n`);
	process.exit(1);
}
